import { Speciality } from './speciality';

export const CLINIC_STATES = ['ACTIVE', 'INACTIVE', 'IN_REVIEW'] as const;
export type ClinicState = (typeof CLINIC_STATES)[number];

export const CLINIC_STATE_LABELS: Record<ClinicState, string> = {
  ACTIVE: 'Aktiv',
  INACTIVE: 'Inaktiv',
  IN_REVIEW: 'In Prüfung',
};

/**
 * Clinic as serialized by the backend entity `com.pluralsight.entity.Clinic`
 * (snake_case field names are kept on purpose to stay wire-compatible).
 */
export interface Clinic {
  clinic_id: number;
  clinic_name: string;
  clinic_description: string;
  clinic_address: string;
  clinic_phone_number: string;
  clinic_state: ClinicState;
  speciality: Speciality;
  /** `LocalTime` → "HH:mm" */
  openingTime: string;
  /** `LocalTime` → "HH:mm" */
  closingTime: string;
}

/** Payload for create/update requests (id is generated by the server). */
export type ClinicDraft = Omit<Clinic, 'clinic_id'>;
